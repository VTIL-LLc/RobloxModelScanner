using System;
using System.Text;

using RMS.Site.Common.Implementation;
using RMS.Site.Common.Models;

using RMS.Configuration.Site.Infrastructure;

namespace RMS.Configuration.Site
{
    /// <summary>
    /// The editor: a manifest as text, with the deployer's reading of it beside it.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The whole file is edited at once. These files are between six and eleven kilobytes and around half of
    /// each is the comment explaining the format, so an operator who is changing one value is also reading the
    /// file -- which is the point. A field-per-setting form would hide the text they are actually responsible
    /// for, and would be a second implementation of the format to keep in step with the deployer's.
    /// </para>
    /// <para>
    /// A save is checked before it is written, and the check is the deployer's own reading of the format rather
    /// than this page's opinion of it. A text the deployer would refuse is answered with the problems and is not
    /// written, so the file on disk is either the old text or a text the deployment can still run.
    /// </para>
    /// <para>
    /// A write that succeeds ends in a redirect, which is what stops a refresh from writing the same text a
    /// second time. A check, and a write that was refused, render in place instead: the text an operator typed
    /// is theirs and is never silently replaced by the file's contents, and that is the difference between an
    /// editor somebody uses and a text editor plus a deployment.
    /// </para>
    /// <para>
    /// No region on this page refreshes itself. A region that replaced the text area while it was being typed
    /// into would be worse than showing a file that is a few seconds old.
    /// </para>
    /// </remarks>
    public class Editor : ConfigurationPage
    {
        /// <summary>
        /// The longest manifest name this page will consider.
        /// </summary>
        private const int MaximumNameLength = 32;

        /// <summary>
        /// The longest hash this page will read.
        /// </summary>
        /// <remarks>
        /// A SHA-256 is sixty-four characters in hexadecimal. This is twice that, because the value is compared
        /// rather than parsed and a length check is the only thing it needs.
        /// </remarks>
        private const int MaximumHashLength = 128;

        /// <summary>
        /// The longest verb this page will read from a submit button.
        /// </summary>
        private const int MaximumActionLength = 16;

        /// <summary>
        /// Gets the title shown in the browser tab.
        /// </summary>
        protected override string PageTitle
        {
            get { return "Edit — " + Settings.Title; }
        }

        /// <summary>
        /// Renders the page.
        /// </summary>
        /// <param name="e">The event data.</param>
        protected override void OnLoad(EventArgs e)
        {
            base.OnLoad(e);

            WriteDocument(PageTitle, Navigation(), RenderBody());
        }

        /// <summary>
        /// Builds the page's body.
        /// </summary>
        /// <returns>The markup.</returns>
        private string RenderBody()
        {
            string name = ManifestName();

            if (!IsKnownKind(name))
            {
                return Html.Heading("Edit a manifest", "One of the files this deployment is described by.")
                       + Html.Alert(
                           "warning",
                           "That is not one of the manifests this console edits.",
                           "The files this console writes are the requirements, the build and the services "
                           + "manifests. The plan is generated by the deployer, so a change made to it here "
                           + "would be lost at the next deployment.");
            }

            string notice = string.Empty;
            string failure = null;
            ManifestWriteResultView result = null;

            if (Request.HttpMethod == "POST")
            {
                if (!CsrfToken.Verify(Session, Request.Form[CsrfToken.FieldName]))
                {
                    // A post without the token is either a form that came from somewhere else or a session that
                    // lapsed between rendering the page and pressing the button. Both are refusals, and the
                    // difference is not one this page can act on. The text that was sent is not kept, because a
                    // post this page did not serve is not a post this page should be echoing back.
                    Store.Audit(
                        "Refused",
                        "/Editor.aspx",
                        "A manifest was posted without a valid anti-forgery token.",
                        IsSignedIn ? CurrentUser.Username : string.Empty,
                        ClientAddress);

                    notice = null;
                    failure = Html.Alert(
                        "warning",
                        "That form could not be accepted.",
                        "The page it came from is no longer the one this session is holding, which happens when "
                        + "a sign-in lapses while a form is open. Reload the page and make the change again.");
                }
                else
                {
                    ApplyPost(name, ref notice, ref failure, ref result);
                }
            }
            else
            {
                notice = DescribeStatus(ReadQuery("status", 32));
            }

            ServiceResult<ManifestDocumentView> document = LoadManifest(name);

            if (!document.IsSuccess)
            {
                // The failure already rendered, when there was one, is kept: a save that failed because the
                // service went away and a reload that failed for the same reason are one fault, and the first
                // sentence about it is the one that says what was being attempted.
                return Html.Heading("That manifest", string.Empty)
                       + (failure ?? string.Empty)
                       + RenderFailure(document);
            }

            if (!document.Value.Editable)
            {
                return Html.Heading("That manifest", string.Empty)
                       + Html.Alert(
                           "warning",
                           "That file is generated by the deployer.",
                           "It is written every time the deployer runs, so a change made here would be "
                           + "overwritten without a word. The services manifest is what it is generated from.")
                       + "<p>" + Html.Link("/Plan.aspx", "See the plan") + "</p>";
            }

            ServiceResult<VocabularyView> vocabulary = LoadVocabulary();

            VocabularySectionView section = vocabulary.IsSuccess
                ? ConfigurationService.SectionFor(vocabulary.Value, name)
                : null;

            return Html.Heading(
                       "Editing " + document.Value.Name,
                       "The file as it stands, and the keys it may carry. Checking is free and writes nothing; "
                       + "saving is refused when the deployer could not read the result, and the text is kept so "
                       + "that a refusal costs nothing but the correction.")
                   + (failure ?? string.Empty)
                   + ConfigurationViews.Editor(
                       document.Value,
                       result,
                       section,
                       notice,
                       CsrfToken.RenderHidden(Session));
        }

        /// <summary>
        /// Applies a posted check or write.
        /// </summary>
        /// <param name="name">The manifest's name.</param>
        /// <param name="notice">Receives a sentence to show above the editor.</param>
        /// <param name="failure">Receives the markup for a call that failed, when one did.</param>
        /// <param name="result">Receives what the service said, when it answered with a result.</param>
        /// <remarks>
        /// A write that was accepted redirects and does not return. Everything else fills one of the three
        /// outputs and lets the page render, because in every one of those cases there is a text worth keeping
        /// in front of the operator: either the text they sent, which the service's answer carries back line by
        /// line, or the file on disk.
        /// </remarks>
        private void ApplyPost(
            string name,
            ref string notice,
            ref string failure,
            ref ManifestWriteResultView result)
        {
            string text;

            if (!TryReadManifestText(out text))
            {
                // Too large to be one of these files, and too large to render. The file is reloaded and the
                // text is not: showing the first part of it as though it were the whole thing would invite
                // somebody to save a truncated file, which is the one outcome worse than losing the text.
                notice = "That text is larger than the largest manifest this console will send, so nothing was "
                         + "written and the text was not kept.";

                return;
            }

            bool saving = string.Equals(
                ReadField("action", MaximumActionLength),
                "save",
                StringComparison.Ordinal);

            ServiceResult<ManifestWriteResultView> outcome = saving
                ? SaveManifest(name, text, ReadField("hash", MaximumHashLength))
                : CheckManifest(name, text);

            if (!outcome.IsSuccess)
            {
                failure = RenderFailure(outcome);

                return;
            }

            if (saving && outcome.Value != null && outcome.Value.Written)
            {
                RedirectToSelf(name);
            }

            result = outcome.Value;
        }

        /// <summary>
        /// Sends the operator back to this page with no text posted.
        /// </summary>
        /// <param name="name">The manifest's name.</param>
        /// <remarks>
        /// A redirect rather than a rendered answer, because the write has already happened: without it, a
        /// refresh would post the same text again, and the hash the form carries would have been left behind by
        /// the write, so a refresh would be refused -- an operator would see a successful save followed by a
        /// warning that the file had changed under them.
        /// </remarks>
        private void RedirectToSelf(string name)
        {
            Response.Redirect(
                "/Editor.aspx?name=" + Uri.EscapeDataString(name) + "&status=saved",
                endResponse: true);
        }

        /// <summary>
        /// Reads the manifest this page is editing.
        /// </summary>
        /// <returns>The name.</returns>
        /// <remarks>
        /// A post carries the name in a field, because the form deliberately posts to an address with no query
        /// string on it: a page that posted back to its own query string would be a page whose destination came
        /// from the caller.
        /// </remarks>
        private string ManifestName()
        {
            return Request.HttpMethod == "POST"
                ? ReadField("name", MaximumNameLength)
                : ReadQuery("name", MaximumNameLength);
        }

        /// <summary>
        /// Turns the status a redirect carried into a sentence.
        /// </summary>
        /// <param name="status">The status.</param>
        /// <returns>The sentence, which is empty for anything unrecognised.</returns>
        /// <remarks>
        /// Only one status exists, and it is the one the redirect produces. A value that is not it is treated as
        /// nothing at all rather than as an error, because the status is decoration on a page that is already
        /// showing the file: an address somebody edited by hand is not a fault worth a message.
        /// </remarks>
        private static string DescribeStatus(string status)
        {
            if (string.Equals(status, "saved", StringComparison.Ordinal))
            {
                return "Saved. What is below is the file as it now stands, read back from disk. Run the "
                       + "deployer to turn a change to the services manifest into a plan.";
            }

            return string.Empty;
        }
    }
}
