using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

using RMS.Configuration.Service.Enums;
using RMS.Configuration.Service.Interfaces;
using RMS.Configuration.Service.Models;
using RMS.Configuration.Service.Options;

using RMS.ServiceModel.Models;

namespace RMS.Configuration.Service.Implementation;

/// <summary>
/// Checks a parsed manifest against the format the deployer reads.
/// </summary>
/// <remarks>
/// <para>
/// Every rule here is either a rule <c>rmsdeploy.c</c> enforces or a rule it silently does not. The second kind
/// is the reason this class exists at all: the deployer ignores a key it does not recognise without a word, drops
/// an environment pair with no equals sign, reads a non-numeric delay as zero, falls back to <c>always</c> for a
/// restart policy it cannot parse, and lets a later duplicate key shadow an earlier one. Each of those produces a
/// deployment that runs and does something other than what the file says, which is worse than a deployment that
/// refuses to start.
/// </para>
/// <para>
/// The validator also derives the things a section's view needs and the reader cannot know: which entry is its
/// kind, which is its platform list and which of its entries is worth showing as a one-line description. Doing it
/// here means the reader stays purely lexical, which is what makes it a faithful copy of the C parser.
/// </para>
/// <para>
/// The document is modified in place and its problems are replaced rather than appended to, so that checking one
/// document twice does not double every message.
/// </para>
/// </remarks>
public sealed class ManifestValidator : IManifestValidator
{
    /// <summary>
    /// The longest a description may be for the summary role, in characters.
    /// </summary>
    /// <remarks>
    /// The overview shows one line per section. A description long enough to fill a paragraph would be truncated
    /// by the browser rather than by this, which is the wrong place for that decision, so a section whose
    /// description is longer keeps its kind as its summary instead.
    /// </remarks>
    private const int SummaryLimit = 120;

    private readonly string _repositoryRoot;
    private readonly ILogger<ManifestValidator> _logger;

    /// <summary>
    /// Initializes a new instance of the <see cref="ManifestValidator"/> class.
    /// </summary>
    /// <param name="options">The bound options, which carry the repository root.</param>
    /// <param name="logger">The logger used to record a build step whose project is not there.</param>
    public ManifestValidator(IOptions<ConfigurationOptions> options, ILogger<ManifestValidator> logger)
    {
        ArgumentNullException.ThrowIfNull(options);

        _repositoryRoot = options.Value.RepositoryRoot;
        _logger = logger;
    }

    /// <inheritdoc />
    public void Validate(ManifestDocument document)
    {
        ArgumentNullException.ThrowIfNull(document);

        document.Problems.Clear();

        // Structural complaints come from the reader, which recorded them on the line that caused them. They are
        // captured before the lines are cleared -- clearing is what keeps a second check from doubling every
        // message, and it would otherwise take the reader's own messages with it, leaving a file that cannot be
        // parsed at all reporting nothing wrong.
        List<(int Line, string Message)> structural = [];

        foreach (ManifestLine line in document.Lines)
        {
            if (line.Kind == ManifestLineKind.Malformed && line.Problem.Length > 0)
                structural.Add((line.Number, line.Problem));
        }

        foreach (ManifestLine line in document.Lines)
            line.Problem = string.Empty;

        foreach ((int line, string message) in structural)
            Report(document, ProblemSeverity.Error, line, string.Empty, string.Empty, message);

        if (document.Unreadable.Length > 0)
        {
            Report(
                document,
                ProblemSeverity.Error,
                0,
                string.Empty,
                string.Empty,
                "This manifest could not be read, so nothing in it has been checked.");
        }

        // The plan is generated, not written. Checking it against the hand-written vocabulary would report a file
        // that is not meant to satisfy it, which would be a complaint that can never be acted on.
        if (document.Kind == ManifestKind.Plan)
        {
            Report(
                document,
                ProblemSeverity.Note,
                0,
                string.Empty,
                string.Empty,
                "This file is generated by the deployer. It is shown for reference and is not checked or written "
                + "by this console.");

            document.Editable = false;
            Sort(document);

            return;
        }

        if (!document.Exists && document.Path.Length > 0)
        {
            Report(
                document,
                ProblemSeverity.Note,
                0,
                string.Empty,
                string.Empty,
                $"There is no file at {document.Path}, so the deployer reports this part of the plan as absent.");
        }

        CheckFile(document);
        CheckDuplicateNames(document);

        VocabularySection vocabulary = DeployerVocabulary.For(document.Kind);

        foreach (ManifestSectionView section in document.Sections)
            CheckSection(document, vocabulary, section);

        Sort(document);
    }

    /// <summary>
    /// Checks the document as a whole.
    /// </summary>
    /// <param name="document">The document to check.</param>
    private static void CheckFile(ManifestDocument document)
    {
        if (document.Sections.Count > DeployerLimits.MaximumSections)
        {
            Report(
                document,
                ProblemSeverity.Error,
                document.Sections[DeployerLimits.MaximumSections].Line,
                string.Empty,
                string.Empty,
                $"This file has {document.Sections.Count} sections and the deployer holds at most "
                + $"{DeployerLimits.MaximumSections}. It refuses the file at the first section past the limit.");
        }

        if (document.Sections.Count == 0 && document.Exists && document.Lines.Count > 0)
        {
            Report(
                document,
                ProblemSeverity.Error,
                0,
                string.Empty,
                string.Empty,
                "This file has no sections, so the deployer reads nothing out of it. Every entry has to sit "
                + "inside a [section] header.");
        }

        // A repeated section name is not an error to the deployer -- it keeps both, and reads both. It is
        // reported anyway, because the two are then indistinguishable in every message the deployer prints, and a
        // message that names a section cannot be acted on when it names two of them.
        Dictionary<string, int> firstLineById = new(StringComparer.OrdinalIgnoreCase);

        foreach (ManifestSectionView section in document.Sections)
        {
            if (firstLineById.TryGetValue(section.Id, out int firstLine))
            {
                Report(
                    document,
                    ProblemSeverity.Warning,
                    section.Line,
                    section.Id,
                    string.Empty,
                    $"[{section.Id}] already appeared at line {firstLine}, and the deployer reads both. Every "
                    + "message about either of them will name the same section.");
            }
            else
            {
                firstLineById[section.Id] = section.Line;
            }
        }
    }

    /// <summary>
    /// Checks for two services claiming the same name or the same port.
    /// </summary>
    /// <param name="document">The document to check.</param>
    /// <remarks>
    /// Only the services manifest has names and ports, and two of either is a deployment that silently does
    /// something the file does not say: one service definition overwrites the other's registration, or one site
    /// fails to start because the port is already taken.
    /// </remarks>
    private static void CheckDuplicateNames(ManifestDocument document)
    {
        if (document.Kind != ManifestKind.Services) return;

        Dictionary<string, int> firstByName = new(StringComparer.OrdinalIgnoreCase);
        Dictionary<string, int> firstByPort = new(StringComparer.OrdinalIgnoreCase);

        foreach (ManifestSectionView section in document.Sections)
        {
            string name = Value(section, DeployerVocabulary.NameKey);
            if (name.Length == 0) name = section.Id;

            if (firstByName.TryGetValue(name, out int nameLine))
            {
                Report(
                    document,
                    ProblemSeverity.Error,
                    section.Line,
                    section.Id,
                    DeployerVocabulary.NameKey,
                    $"The name '{name}' is already used by the section at line {nameLine}. The second service "
                    + "would overwrite the first one's registration.");
            }
            else
            {
                firstByName[name] = section.Line;
            }

            string port = AnyValue(section, DeployerVocabulary.PortKey);

            if (port.Length == 0) continue;

            if (firstByPort.TryGetValue(port, out int portLine))
            {
                Report(
                    document,
                    ProblemSeverity.Error,
                    section.Line,
                    section.Id,
                    DeployerVocabulary.PortKey,
                    $"Port {port} is already used by the section at line {portLine}. Two sites cannot listen on "
                    + "one port, and the second one will not start.");
            }
            else
            {
                firstByPort[port] = section.Line;
            }
        }
    }

    /// <summary>
    /// Checks one section and everything in it.
    /// </summary>
    /// <param name="document">The document being checked.</param>
    /// <param name="vocabulary">The vocabulary the document is written in.</param>
    /// <param name="section">The section to check.</param>
    private void CheckSection(
        ManifestDocument document,
        VocabularySection vocabulary,
        ManifestSectionView section)
    {
        if (section.Id.Length == 0)
        {
            Report(
                document,
                ProblemSeverity.Error,
                section.Line,
                section.Id,
                string.Empty,
                "The section has no name, and the deployer uses the name in every message about it. Write an "
                + "identifier between the brackets.");
        }
        else if (section.Id.Length > DeployerLimits.MaximumIdentifierLength)
        {
            Report(
                document,
                ProblemSeverity.Error,
                section.Line,
                section.Id,
                string.Empty,
                $"The section name is {section.Id.Length} characters and the deployer holds at most "
                + $"{DeployerLimits.MaximumIdentifierLength}.");
        }

        // Every key is checked before the section's own rules, so that a misspelling is reported even when the
        // section is otherwise complete. A misspelling is the mistake that leaves the file valid, which is why it
        // is the one that has to be caught here rather than on the machine that fails to deploy.
        HashSet<string> seen = new(StringComparer.Ordinal);

        foreach (ManifestEntryView entry in section.Entries)
            CheckEntry(document, vocabulary, section, entry, seen);

        if (section.Entries.Count > DeployerLimits.MaximumKeysPerSection)
        {
            Report(
                document,
                ProblemSeverity.Error,
                section.Entries[DeployerLimits.MaximumKeysPerSection].Line,
                section.Id,
                string.Empty,
                $"This section has {section.Entries.Count} keys and the deployer holds at most "
                + $"{DeployerLimits.MaximumKeysPerSection}.");
        }

        section.Kind = Value(section, DeployerVocabulary.KindKey);
        section.Platforms = Value(section, DeployerVocabulary.PlatformsKey);

        switch (document.Kind)
        {
            case ManifestKind.Requirements:
                CheckRequirement(document, vocabulary, section);
                break;

            case ManifestKind.Build:
                CheckBuildStep(document, vocabulary, section);
                break;

            case ManifestKind.Services:
                CheckService(document, section);
                break;
        }

        if (section.Summary.Length == 0)
        {
            section.Summary = section.Kind.Length > 0 ? section.Kind : "a section with no kind";
        }
    }

    /// <summary>
    /// Checks one key and its value.
    /// </summary>
    /// <param name="document">The document being checked.</param>
    /// <param name="vocabulary">The vocabulary the document is written in.</param>
    /// <param name="section">The section the entry is in.</param>
    /// <param name="entry">The entry to check.</param>
    /// <param name="seen">The qualified spellings already seen in this section.</param>
    private static void CheckEntry(
        ManifestDocument document,
        VocabularySection vocabulary,
        ManifestSectionView section,
        ManifestEntryView entry,
        HashSet<string> seen)
    {
        string qualified = entry.Platform.Length > 0 ? entry.Platform + "." + entry.Key : entry.Key;

        if (qualified.Length > DeployerLimits.MaximumIdentifierLength)
        {
            entry.Recognised = false;

            Report(
                document,
                ProblemSeverity.Error,
                entry.Line,
                section.Id,
                entry.Key,
                $"The key '{qualified}' is longer than the {DeployerLimits.MaximumIdentifierLength} characters "
                + "the deployer holds, so it refuses the file.");
        }

        VocabularyEntry? definition = DeployerVocabulary.Find(vocabulary, entry.Key);

        if (entry.Platform.Length > 0 && !DeployerVocabulary.IsPlatformName(entry.Platform))
        {
            entry.Recognised = false;

            Report(
                document,
                ProblemSeverity.Error,
                entry.Line,
                section.Id,
                entry.Key,
                $"'{entry.Platform}' is not a platform. The deployer resolves a key against "
                + $"'{string.Join("', '", DeployerVocabulary.Platforms)}', so '{qualified}' names a platform that "
                + "does not exist, which is the same as not writing the key at all.");
        }

        if (definition is null)
        {
            entry.Recognised = false;

            Report(
                document,
                ProblemSeverity.Error,
                entry.Line,
                section.Id,
                entry.Key,
                $"The deployer does not read '{entry.Key}' in this file, so the line has no effect. Check the "
                + "spelling against the key list.");
        }
        else if (entry.Platform.Length > 0 && !definition.PerPlatform)
        {
            entry.Recognised = false;

            Report(
                document,
                ProblemSeverity.Error,
                entry.Line,
                section.Id,
                entry.Key,
                $"'{entry.Key}' is read exactly as written, so '{qualified}' hides it rather than overriding it. "
                + "Write it without the platform prefix.");
        }

        if (!seen.Add(qualified))
        {
            Report(
                document,
                ProblemSeverity.Error,
                entry.Line,
                section.Id,
                entry.Key,
                $"'{qualified}' is written more than once in this section. The deployer keeps the first and "
                + "ignores this one.");
        }

        if (definition is null) return;

        // The value's own length. A path has a longer home than a version, and a value that overflows its buffer
        // is refused by the deployer with a message that names the section rather than the line.
        //
        // Characters rather than bytes, which is the one place this validator is knowingly approximate: the C
        // buffers count bytes, so a value of non-ASCII text sits closer to its limit than its length suggests.
        // The character count is still the useful number to report, because it is the one an editor shows.
        int maximum = definition.MaximumLength > 0
            ? definition.MaximumLength
            : DeployerLimits.MaximumValueLength;

        if (entry.Value.Length > maximum)
        {
            Report(
                document,
                ProblemSeverity.Error,
                entry.Line,
                section.Id,
                entry.Key,
                $"The value is {entry.Value.Length} characters and '{entry.Key}' holds at most {maximum}.");
        }

        // The set a `kind` may take depends on which file it is in, so the kind is reported by RequireKind with
        // the list that belongs to this file rather than by this generic check with a union of every list. A kind
        // outside the union would otherwise be reported twice, in two slightly different sentences.
        bool reportedByValue =
            definition.Values.Count > 0 &&
            entry.Value.Length > 0 &&
            !string.Equals(entry.Key, DeployerVocabulary.KindKey, StringComparison.Ordinal) &&
            !Accepts(definition, entry.Value);

        if (reportedByValue)
        {
            Report(
                document,
                ProblemSeverity.Error,
                entry.Line,
                section.Id,
                entry.Key,
                $"'{entry.Value}' is not one of the values '{entry.Key}' accepts. It accepts "
                + $"{string.Join(", ", definition.Values)}.");
        }
    }

    /// <summary>
    /// Checks a requirement's own rules.
    /// </summary>
    /// <param name="document">The document being checked.</param>
    /// <param name="vocabulary">The vocabulary the document is written in.</param>
    /// <param name="section">The section to check.</param>
    private static void CheckRequirement(
        ManifestDocument document,
        VocabularySection vocabulary,
        ManifestSectionView section)
    {
        RequireKind(document, vocabulary, section);

        if (section.Kind.Length == 0) return;

        string url = AnyValue(section, DeployerVocabulary.UrlKey);

        if (url.Length > 0 && !url.StartsWith("https://", StringComparison.OrdinalIgnoreCase))
        {
            Report(
                document,
                ProblemSeverity.Error,
                LineOf(section, DeployerVocabulary.UrlKey),
                section.Id,
                DeployerVocabulary.UrlKey,
                $"The deployer downloads over https only and refuses '{url}'. Its TLS settings are chosen from "
                + "the scheme, so an http URL is not a weaker download but no download at all.");
        }

        string strip = AnyValue(section, DeployerVocabulary.StripKey);

        if (strip.Length > 0 && !int.TryParse(strip, out _))
        {
            Report(
                document,
                ProblemSeverity.Warning,
                LineOf(section, DeployerVocabulary.StripKey),
                section.Id,
                DeployerVocabulary.StripKey,
                $"'{strip}' is not a whole number, and the deployer reads this key as one. It will be read as 0, "
                + "which keeps every leading directory component of the archive.");
        }

        string installDirectory = AnyValue(section, DeployerVocabulary.InstallDirectoryKey);

        if (installDirectory.StartsWith("http", StringComparison.OrdinalIgnoreCase) ||
            Value(section, DeployerVocabulary.ProvidesKey).StartsWith("http", StringComparison.OrdinalIgnoreCase))
        {
            Report(
                document,
                ProblemSeverity.Warning,
                LineOf(section, DeployerVocabulary.InstallDirectoryKey),
                section.Id,
                DeployerVocabulary.InstallDirectoryKey,
                "This looks like a URL, but the deployer reads it as a directory and will create a directory "
                + "whose name begins 'http'.");
        }

        bool installable =
            AnyValue(section, DeployerVocabulary.UrlKey).Length > 0 ||
            AnyValue(section, DeployerVocabulary.InstallKey).Length > 0;

        bool verifiable =
            AnyValue(section, DeployerVocabulary.VerifyToolKey).Length > 0 ||
            AnyValue(section, DeployerVocabulary.VerifyPathKey).Length > 0 ||
            AnyValue(section, DeployerVocabulary.VerifyKey).Length > 0;

        if (!installable && !verifiable)
        {
            Report(
                document,
                ProblemSeverity.Warning,
                section.Line,
                section.Id,
                string.Empty,
                "This requirement has neither a way to be installed nor a way to be verified. The deployer will "
                + "report it as missing and will not be able to make it present.");
        }
        else if (!verifiable)
        {
            Report(
                document,
                ProblemSeverity.Note,
                section.Line,
                section.Id,
                string.Empty,
                "Nothing here decides whether the requirement is already present, so the deployer will download "
                + "or install it every time it runs -- unless it is a kind whose presence its own toolchain "
                + "search resolves.");
        }

        section.Summary = DescribeSection(section, "requirement");
    }

    /// <summary>
    /// Checks a build step's own rules.
    /// </summary>
    /// <param name="document">The document being checked.</param>
    /// <param name="vocabulary">The vocabulary the document is written in.</param>
    /// <param name="section">The section to check.</param>
    private void CheckBuildStep(
        ManifestDocument document,
        VocabularySection vocabulary,
        ManifestSectionView section)
    {
        RequireKind(document, vocabulary, section);

        if (section.Kind.Length == 0) return;

        bool shell = section.Kind.Equals("shell", StringComparison.OrdinalIgnoreCase);
        string path = Value(section, DeployerVocabulary.PathKey);

        if (path.Length == 0)
        {
            Report(
                document,
                shell ? ProblemSeverity.Error : ProblemSeverity.Warning,
                section.Line,
                section.Id,
                DeployerVocabulary.PathKey,
                shell
                    ? "A shell step's path is the command to run, and without one there is nothing to run."
                    : "This step has nothing to build, so the deployer will report it as not present and skip "
                      + "it. That is the right spelling for a project that does not exist yet.");
        }
        else if (shell)
        {
            Report(
                document,
                ProblemSeverity.Note,
                section.Line,
                section.Id,
                DeployerVocabulary.PathKey,
                "A shell step runs its command verbatim through the platform's shell. Nothing in it is expanded "
                + "or checked, which makes it the one kind whose mistakes the deployer cannot catch.");
        }
        else
        {
            CheckBuildPath(document, section, path, LineOf(section, DeployerVocabulary.PathKey));
        }

        section.Summary = DescribeSection(section, "build step");
    }

    /// <summary>
    /// Checks that a build step's project is where it says it is.
    /// </summary>
    /// <param name="document">The document being checked.</param>
    /// <param name="section">The section being checked.</param>
    /// <param name="path">The declared path.</param>
    /// <param name="line">The line the path was written on.</param>
    /// <remarks>
    /// Only checked when the repository root is configured, because a path with no root to resolve it against is
    /// a path about a machine this service knows nothing about. The result is a warning and never an error: a step
    /// whose project is missing is exactly how this repository describes work that has not been written yet.
    /// </remarks>
    private void CheckBuildPath(
        ManifestDocument document,
        ManifestSectionView section,
        string path,
        int line)
    {
        if (_repositoryRoot.Length == 0) return;

        string resolved;

        try
        {
            resolved = Path.IsPathRooted(path)
                ? Path.GetFullPath(path)
                : Path.GetFullPath(Path.Combine(_repositoryRoot, path));
        }
        catch (Exception exception) when (exception is ArgumentException or NotSupportedException or PathTooLongException)
        {
            Report(
                document,
                ProblemSeverity.Error,
                line,
                section.Id,
                DeployerVocabulary.PathKey,
                $"'{path}' cannot be turned into a path: {exception.Message}");

            return;
        }

        if (File.Exists(resolved) || Directory.Exists(resolved)) return;

        _logger.LogDebug("The build step {Section} names {Path}, which does not exist yet.", section.Id, resolved);

        Report(
            document,
            ProblemSeverity.Warning,
            line,
            section.Id,
            DeployerVocabulary.PathKey,
            $"There is nothing at {resolved}, so the deployer will report this step as not present and skip it. "
            + "The path is resolved against the repository root this service was started with.");
    }

    /// <summary>
    /// Checks a service's own rules.
    /// </summary>
    /// <param name="document">The document being checked.</param>
    /// <param name="section">The section to check.</param>
    private static void CheckService(ManifestDocument document, ManifestSectionView section)
    {
        string name = Value(section, DeployerVocabulary.NameKey);
        if (name.Length == 0) name = section.Id;

        try
        {
            ServicePlan.ValidateName(name);
        }
        catch (InvalidOperationException exception)
        {
            Report(
                document,
                ProblemSeverity.Error,
                LineOf(section, DeployerVocabulary.NameKey),
                section.Id,
                DeployerVocabulary.NameKey,
                $"{exception.Message} The name reaches a file system path, a service definition and a directory "
                + "under the log root.");
        }

        bool runs = AnyValue(section, DeployerVocabulary.ExecutableKey).Length > 0;
        bool serves = AnyValue(section, DeployerVocabulary.WebsiteKey).Length > 0;

        if (!runs && !serves)
        {
            Report(
                document,
                ProblemSeverity.Error,
                section.Line,
                section.Id,
                string.Empty,
                "This service has neither an executable nor a web site, so there is nothing for the deployer to "
                + "register. Write 'executable' for a process, or 'website' for a site the platform serves.");
        }

        // The restart policy's value is checked with the rest of the vocabulary, against the closed set the
        // supervisor understands. It is not checked again here: one mistake reported twice reads as two
        // mistakes, which is how an operator learns to skim.
        CheckSeconds(document, section, DeployerVocabulary.RestartDelayKey);
        CheckSeconds(document, section, DeployerVocabulary.MaximumRestartDelayKey);
        CheckSeconds(document, section, DeployerVocabulary.StopTimeoutKey);
        CheckEnvironmentPairs(document, section);
        CheckPort(document, section, serves);

        section.Summary = DescribeSection(section, "service");
    }

    /// <summary>
    /// Checks a delay or a timeout that the deployer reads as a number.
    /// </summary>
    /// <param name="document">The document being checked.</param>
    /// <param name="section">The section being checked.</param>
    /// <param name="key">The key to check.</param>
    private static void CheckSeconds(ManifestDocument document, ManifestSectionView section, string key)
    {
        string value = AnyValue(section, key);

        if (value.Length == 0) return;

        if (!int.TryParse(value, out int seconds))
        {
            Report(
                document,
                ProblemSeverity.Warning,
                LineOf(section, key),
                section.Id,
                key,
                $"'{value}' is not a whole number of seconds, and the deployer reads this key as one. The value is "
                + "replaced by the key's default rather than refused, so the service starts with a delay nobody "
                + "wrote.");

            return;
        }

        if (seconds < 1)
        {
            Report(
                document,
                ProblemSeverity.Warning,
                LineOf(section, key),
                section.Id,
                key,
                $"The deployer raises {seconds} to 1, because a delay or a grace period of zero is a kill with no "
                + "request before it.");
        }
    }

    /// <summary>
    /// Checks the environment pairs a service declares.
    /// </summary>
    /// <param name="document">The document being checked.</param>
    /// <param name="section">The section being checked.</param>
    /// <remarks>
    /// The pairs are semicolon separated and each has to be a <c>NAME=VALUE</c>. The deployer drops an entry
    /// without an equals sign in silence, which is how a service ends up running without a variable whose line is
    /// present and looks correct.
    /// </remarks>
    private static void CheckEnvironmentPairs(ManifestDocument document, ManifestSectionView section)
    {
        string environment = AnyValue(section, DeployerVocabulary.EnvironmentKey);

        if (environment.Length == 0) return;

        int line = LineOf(section, DeployerVocabulary.EnvironmentKey);
        List<string> names = [];

        foreach (string part in environment.Split(DeployerVocabulary.ListSeparator))
        {
            string pair = part.Trim();

            if (pair.Length == 0) continue;

            int separator = pair.IndexOf('=');

            if (separator <= 0)
            {
                Report(
                    document,
                    ProblemSeverity.Error,
                    line,
                    section.Id,
                    DeployerVocabulary.EnvironmentKey,
                    $"'{pair}' has no name, so the deployer drops it without a word. Every entry has to be written "
                    + "NAME=VALUE.");

                continue;
            }

            string name = pair[..separator].Trim();

            if (names.Contains(name, StringComparer.Ordinal))
            {
                Report(
                    document,
                    ProblemSeverity.Warning,
                    line,
                    section.Id,
                    DeployerVocabulary.EnvironmentKey,
                    $"{name} is set twice in this list. The plan keeps the last one, which is the opposite of what "
                    + "a reader of the list would assume.");
            }

            names.Add(name);
        }
    }

    /// <summary>
    /// Checks a web site's port.
    /// </summary>
    /// <param name="document">The document being checked.</param>
    /// <param name="section">The section being checked.</param>
    /// <param name="serves">Whether the section serves a directory.</param>
    private static void CheckPort(ManifestDocument document, ManifestSectionView section, bool serves)
    {
        string port = AnyValue(section, DeployerVocabulary.PortKey);

        if (port.Length == 0)
        {
            if (serves)
            {
                Report(
                    document,
                    ProblemSeverity.Warning,
                    section.Line,
                    section.Id,
                    DeployerVocabulary.PortKey,
                    "This service serves a directory but names no port, so the platform will have to choose one. "
                    + "A site on a port nobody wrote down is a site nobody can reach.");
            }

            return;
        }

        if (!serves)
        {
            Report(
                document,
                ProblemSeverity.Warning,
                LineOf(section, DeployerVocabulary.PortKey),
                section.Id,
                DeployerVocabulary.PortKey,
                "A port is written with no web site to serve, so the deployer has nothing to use it for.");
        }

        if (!int.TryParse(port, out int number) || number is < 1 or > 65535)
        {
            Report(
                document,
                ProblemSeverity.Error,
                LineOf(section, DeployerVocabulary.PortKey),
                section.Id,
                DeployerVocabulary.PortKey,
                $"'{port}' is not a port between 1 and 65535.");
        }
    }

    /// <summary>
    /// Requires that a section names a kind, and that the kind is one the deployer knows.
    /// </summary>
    /// <param name="document">The document being checked.</param>
    /// <param name="vocabulary">The vocabulary the document is written in.</param>
    /// <param name="section">The section to check.</param>
    private static void RequireKind(
        ManifestDocument document,
        VocabularySection vocabulary,
        ManifestSectionView section)
    {
        string kind = Value(section, DeployerVocabulary.KindKey);

        if (kind.Length == 0)
        {
            Report(
                document,
                ProblemSeverity.Error,
                section.Line,
                section.Id,
                DeployerVocabulary.KindKey,
                $"This section has no kind, and the deployer refuses the file when it sees one without. Write "
                + $"'kind = ' with one of {string.Join(", ", vocabulary.Kinds)}.");

            return;
        }

        if (!Contains(vocabulary.Kinds, kind))
        {
            Report(
                document,
                ProblemSeverity.Error,
                LineOf(section, DeployerVocabulary.KindKey),
                section.Id,
                DeployerVocabulary.KindKey,
                $"'{kind}' is not a kind the deployer knows in this file. It knows "
                + $"{string.Join(", ", vocabulary.Kinds)}.");
        }
    }

    /// <summary>
    /// Builds a one-line description of a section for the overview.
    /// </summary>
    /// <param name="section">The section to describe.</param>
    /// <param name="noun">What a section of this file is, used when the file provides no description.</param>
    /// <returns>The sentence to show beside the section's identifier.</returns>
    /// <remarks>
    /// A service has a description and a build step has a note. Both are written for a human, so both are used
    /// here, and a file that provides neither falls back to naming what the section is.
    /// </remarks>
    private static string DescribeSection(ManifestSectionView section, string noun)
    {
        string description = Value(section, DeployerVocabulary.DescriptionKey);

        if (description.Length == 0) description = Value(section, DeployerVocabulary.NoteKey);

        if (description.Length == 0)
        {
            string platforms = section.Platforms.Length > 0 ? " for " + section.Platforms : string.Empty;

            return $"{section.Kind} {noun}{platforms}";
        }

        return description.Length <= SummaryLimit ? description : description[..SummaryLimit] + "...";
    }

    /// <summary>
    /// Reads an unqualified key's value.
    /// </summary>
    /// <param name="section">The section to read from.</param>
    /// <param name="key">The key to read.</param>
    /// <returns>The value, or an empty string when the key is absent.</returns>
    private static string Value(ManifestSectionView section, string key)
    {
        foreach (ManifestEntryView entry in section.Entries)
        {
            if (entry.Platform.Length == 0 && string.Equals(entry.Key, key, StringComparison.Ordinal))
                return entry.Value;
        }

        return string.Empty;
    }

    /// <summary>
    /// Reads the value the deployer would use for a platform-aware key.
    /// </summary>
    /// <param name="section">The section to read from.</param>
    /// <param name="key">The key to read.</param>
    /// <returns>The first platform-qualified value for the key, or the unqualified one, or an empty string.</returns>
    /// <remarks>
    /// Any platform's value will do, because every caller is asking a presence question -- is there a url, is
    /// there an executable -- whose answer does not depend on which platform it is for. The deployer resolves
    /// these one platform at a time; this only has to know whether the key was written at all.
    /// </remarks>
    private static string AnyValue(ManifestSectionView section, string key)
    {
        string qualified = string.Empty;

        foreach (ManifestEntryView entry in section.Entries)
        {
            if (!string.Equals(entry.Key, key, StringComparison.Ordinal)) continue;

            if (entry.Platform.Length == 0) return entry.Value;

            if (qualified.Length == 0) qualified = entry.Value;
        }

        return qualified;
    }

    /// <summary>
    /// Finds the line a key was written on.
    /// </summary>
    /// <param name="section">The section to read from.</param>
    /// <param name="key">The key to find.</param>
    /// <returns>The line, or the section's own line when the key is not written at all.</returns>
    private static int LineOf(ManifestSectionView section, string key)
    {
        foreach (ManifestEntryView entry in section.Entries)
        {
            if (string.Equals(entry.Key, key, StringComparison.Ordinal)) return entry.Line;
        }

        return section.Line;
    }

    /// <summary>
    /// Tests whether a closed set of values admits one.
    /// </summary>
    /// <param name="definition">The vocabulary entry whose values to test.</param>
    /// <param name="value">The value to test.</param>
    /// <returns><see langword="true"/> when the value is one the entry accepts.</returns>
    private static bool Accepts(VocabularyEntry definition, string value)
    {
        foreach (string candidate in definition.Values)
        {
            if (candidate.Equals(value, StringComparison.OrdinalIgnoreCase)) return true;
        }

        return false;
    }

    /// <summary>
    /// Tests whether a set of values contains one, ignoring case.
    /// </summary>
    /// <param name="values">The values to search.</param>
    /// <param name="value">The value to find.</param>
    /// <returns><see langword="true"/> when the value is present.</returns>
    private static bool Contains(IReadOnlyList<string> values, string value)
    {
        foreach (string candidate in values)
        {
            if (candidate.Equals(value, StringComparison.OrdinalIgnoreCase)) return true;
        }

        return false;
    }

    /// <summary>
    /// Records a problem and attributes it to its line.
    /// </summary>
    /// <param name="document">The document the problem is about.</param>
    /// <param name="severity">How badly it matters.</param>
    /// <param name="line">The one-based line, or zero for the file.</param>
    /// <param name="section">The section, or an empty string.</param>
    /// <param name="key">The key, or an empty string.</param>
    /// <param name="message">The sentence to show.</param>
    private static void Report(
        ManifestDocument document,
        ProblemSeverity severity,
        int line,
        string section,
        string key,
        string message)
    {
        document.Problems.Add(new ManifestProblem
        {
            Severity = severity,
            Line = line,
            Section = section,
            Key = key,
            Message = message,
        });

        // The line carries the first thing said about it, so that a line with three complaints is still
        // recognisable in the editor without opening the list.
        if (line <= 0 || line > document.Lines.Count) return;

        ManifestLine target = document.Lines[line - 1];

        if (target.Problem.Length == 0) target.Problem = message;
    }

    /// <summary>
    /// Orders a document's problems: errors first, then line order.
    /// </summary>
    /// <param name="document">The document whose problems are to be ordered.</param>
    private static void Sort(ManifestDocument document)
    {
        document.Problems.Sort(static (left, right) =>
        {
            int bySeverity = right.Severity.CompareTo(left.Severity);
            if (bySeverity != 0) return bySeverity;

            int byLine = left.Line.CompareTo(right.Line);
            if (byLine != 0) return byLine;

            return string.CompareOrdinal(left.Key, right.Key);
        });
    }
