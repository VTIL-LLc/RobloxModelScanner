<#
    ===========================================================================
    RMS CONFIGURATION - THE WRITE PATH
    ===========================================================================
    Invoked by configure.bat, which collects the values from the operator. Every
    value arrives in the process environment and nothing arrives on a command
    line, because a value that had to survive cmd's quoting would not: the
    session cookie this file writes contains a pipe character, and cmd splits a
    line on one wherever it appears outside quotes.

    Inputs, all read from the environment:

      RMS_CRED_DIR        The directory the credential files belong in.
      RMS_CRED_NAMES      ';'-separated file names, in the order they are read.
      RMS_CRED_VARS       ';'-separated variable names holding their values.
      RMS_CRED_GENERATE   ';'-separated file names to generate a value for.
      RMS_CRED_MINIMUM    The shortest credential this stack accepts.
      RMSVALUE_<KEY>      One variable per setting the environment file holds.
      RMS_ENV_BASE        The file to read as the shape of the scanner's .env.
      RMS_ENV_TARGET      The .env to write.
      RMS_ROOT_BASE       The same, for the .env at the repository root.
      RMS_ROOT_TARGET     The .env to write there, or empty to skip that file.
      RMS_HARDEN          '1' to restrict what can read the files written.

    Every output line names a file and reports a length or a count. A value is
    never printed, including the value just written: the operator either knows
    it or can read it from the file, and a console has no memory of what it
    showed.

    Exit codes: 0 written, 4 a failure whose message has already been printed.
#>

$ErrorActionPreference = 'Stop'

# The encoding every file is written with: UTF-8 without a byte order mark. A
# mark would be read as part of the first line of an environment file, and a
# credential file carrying one would never compare equal to the value the
# service reads, which is a failure with no error message anywhere.
$script:NoBom = New-Object System.Text.UTF8Encoding($false)

# The line endings, kept apart so that the file's own ending survives a rewrite
# rather than being normalised into the one this script happens to prefer.
$script:Cr = [string][char]13
$script:Lf = [string][char]10
$script:CrLf = $script:Cr + $script:Lf

<#
    .SYNOPSIS
    Writes one file, without a trailing newline and without a byte order mark.
    .DESCRIPTION
    A credential file holds the value and nothing else, so the text that goes in
    is the text on disk.
    .PARAMETER Path
    The file to write, replaced if it exists.
    .PARAMETER Text
    The exact contents.
#>
function Write-AllText {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)][string]$Text)

    [System.IO.File]::WriteAllText($Path, $Text, $script:NoBom)
}

<#
    .SYNOPSIS
    Collects the settings the caller placed in the environment.
    .DESCRIPTION
    Only variables carrying the caller's prefix are read, and only those whose
    remainder is a well-formed setting name, so an unrelated variable that
    happens to share the prefix cannot enter an environment file.
    .PARAMETER Prefix
    The prefix, which is removed from each name.
    .OUTPUTS
    System.Collections.Hashtable
#>
function Get-EnvironmentValues {
    param([Parameter(Mandatory = $true)][string]$Prefix)

    $values = @{}
    $all = [System.Environment]::GetEnvironmentVariables()

    foreach ($name in $all.Keys) {
        if (-not $name.StartsWith($Prefix, [System.StringComparison]::Ordinal)) { continue }

        $key = $name.Substring($Prefix.Length)
        if ($key -match '^[A-Za-z_][A-Za-z0-9_]*$') {
            $values[$key] = [string]$all[$name]
        }
    }

    # The comma is deliberate: without it the hashtable would be enumerated into
    # the caller's return value, and the caller would receive its entries.
    return , $values
}

<#
    .SYNOPSIS
    Makes a fresh credential.
    .DESCRIPTION
    Both shapes come from the cryptographic generator rather than a seeded one,
    because a credential that can be predicted by anyone who has read this file
    is not a credential.
    .PARAMETER Kind
    guid for a sixteen-byte identifier with dashes, token for forty-eight bytes
    in base64. The deployment guide tells an operator to ask openssl for the
    second, so a value generated here and a value generated by hand are the same
    shape.
    .OUTPUTS
    System.String
#>
function New-CredentialValue {
    param(
        [Parameter(Mandatory = $true)]
        [ValidateSet('guid', 'token')][string]$Kind)

    if ($Kind -eq 'guid') {
        return [guid]::NewGuid().ToString('D')
    }

    $bytes = New-Object byte[] 48
    $generator = New-Object System.Security.Cryptography.RNGCryptoServiceProvider
    try {
        $generator.GetBytes($bytes)
    }
    finally {
        $generator.Dispose()
    }

    return [Convert]::ToBase64String($bytes)
}

<#
    .SYNOPSIS
    Writes every credential file the deployment names.
    .DESCRIPTION
    A credential with no value and no request to generate one is left alone
    rather than created empty: a file that exists and holds nothing reads the
    same to every surface as no file at all, and reports the discovery differently
    later.
    .PARAMETER Directory
    Where the files go, created if it is not there.
    .PARAMETER Names
    The file names, in order.
    .PARAMETER Variables
    The variable holding each value, in the same order.
    .PARAMETER Generate
    File names that are to be given a generated value when none was typed.
    .PARAMETER Minimum
    The shortest value this stack accepts, reported against rather than enforced,
    because the operator may be provisioning for a stack this script does not know.
    .OUTPUTS
    System.Collections.Hashtable holding the file name of each written credential,
    and the value written for it, under the keys Path and Value.
#>
function Write-CredentialFiles {
    param(
        [Parameter(Mandatory = $true)][string]$Directory,
        [Parameter(Mandatory = $true)][string[]]$Names,
        [Parameter(Mandatory = $true)][string[]]$Variables,
        [Parameter(Mandatory = $true)][AllowEmptyCollection()][string[]]$Generate,
        [Parameter(Mandatory = $true)][int]$Minimum)

    $written = @{}
    [void][System.IO.Directory]::CreateDirectory($Directory)

    for ($index = 0; $index -lt $Names.Length; $index++) {
        $name = $Names[$index]
        $value = [System.Environment]::GetEnvironmentVariable($Variables[$index])

        if ([string]::IsNullOrEmpty($value) -and ($Generate -contains $name)) {
            if ($name -eq 'api-key') { $value = New-CredentialValue 'guid' }
            else { $value = New-CredentialValue 'token' }
        }

        if ([string]::IsNullOrEmpty($value)) {
            Write-Host ('  {0,-24} left alone, nothing was entered for it' -f $name)
            continue
        }

        $path = [System.IO.Path]::Combine($Directory, $name)
        $fold = 'created'
        if ([System.IO.File]::Exists($path)) { $fold = 'rewritten' }

        Write-AllText -Path $path -Text $value
        $written[$name] = $value

        $note = ''
        if ($value.Length -lt $Minimum) {
            $note = '   refused by every surface here: shorter than ' + $Minimum
        }

        Write-Host ('  {0,-24} {1}  {2,4} characters{3}' -f $name, $fold, $value.Length, $note)
    }

    return , $written
}

<#
    .SYNOPSIS
    Fills in the settings of one environment file, in place.
    .DESCRIPTION
    The file being written is the shape: its comments, its order and its own line
    ending are kept, and only the value of a setting it already declares is
    replaced. A setting the caller supplied that the file does not declare is not
    added, which is what keeps one set of values usable for two files that hold
    different settings.
    .PARAMETER Base
    The file to read. It is also what a first run copies from, so a deployment
    that has never been configured is filled in from its template.
    .PARAMETER Target
    The file to write.
    .PARAMETER Label
    The name this file is reported under.
    .PARAMETER Values
    The settings, keyed by setting name.
    .PARAMETER Managed
    The settings this caller is allowed to set. A setting on this list that the
    caller did not supply is written as an empty value, which is how a setting
    that was deliberately cleared is told apart from one that was not asked for.
    cmd has no way to pass a variable that is present and empty: setting one to
    nothing removes it from the environment.
    .DESCRIPTION
    A setting is written when this caller supplied it, and it is written as empty
    when it is one this caller owns and did not supply. A setting that is neither
    supplied nor owned is left exactly as the file had it, which is how a value
    that another program in the deployment put there survives this one.
#>
function Update-EnvironmentFile {
    param(
        [Parameter(Mandatory = $true)][string]$Base,
        [Parameter(Mandatory = $true)][string]$Target,
        [Parameter(Mandatory = $true)][string]$Label,
        [Parameter(Mandatory = $true)][hashtable]$Values,
        [Parameter(Mandatory = $true)][AllowEmptyCollection()][string[]]$Managed)

    if (-not [System.IO.File]::Exists($Base)) {
        throw ('nothing to build this file from: ' + $Base + ' does not exist')
    }

    $owned = @{}
    foreach ($key in $Managed) { $owned[$key] = $true }

    $text = [System.IO.File]::ReadAllText($Base)

    $newline = $script:Lf
    if ($text.Contains($script:CrLf)) { $newline = $script:CrLf }

    $out = New-Object System.Collections.Generic.List[string]
    $present = 0
    $changed = 0

    foreach ($line in ($text -split $newline)) {
        if ($line -match '^([A-Za-z_][A-Za-z0-9_]*)=(.*)$') {
            $key = $matches[1]
            if ($owned.ContainsKey($key) -or $Values.ContainsKey($key)) {
                $value = ''
                if ($Values.ContainsKey($key)) { $value = $Values[$key] }
                $replacement = $key + '=' + $value
                if ($replacement -ne $line) { $changed++ }
                $present++
                $out.Add($replacement)
                continue
            }
        }

        $out.Add($line)
    }

    # A file that ended with a line ending splits into a last element that is
    # empty. Joining that back and adding one more would grow the file by a blank
    # line on every run, so the last element is dropped when it is empty and the
    # single ending is added at the end.
    if ($out.Count -gt 0 -and $out[$out.Count - 1] -eq [string]::Empty) {
        $out.RemoveAt($out.Count - 1)
    }

    Write-AllText -Path $Target -Text (($out -join $newline) + $newline)

    Write-Host ('  {0,-24} written  {1} setting(s) it declares, {2} changed' -f $Label, $present, $changed)
}

<#
    .SYNOPSIS
    Restricts each written file to the accounts that have to read it.
    .DESCRIPTION
    Inherited permissions are removed and then exactly three grants are made:
    the operator, who must be able to change a value on the next run; SYSTEM,
    because that is the account the service manager starts a service as when it
    is given no other; and IIS_IUSRS, because every application pool that was not
    given an identity runs as a member of it, and the four sites read their keys
    at request time. Granting anything broader is what this function exists to
    undo, and granting anything narrower breaks a site in a way that looks like a
    wrong key.
    .PARAMETER Targets
    The files to restrict, each with the name it is reported under.
#>
function Set-RestrictedPermissions {
    param([Parameter(Mandatory = $true)][array]$Targets)

    $operator = '*' + [System.Security.Principal.WindowsIdentity]::GetCurrent().User.Value
    $system = '*S-1-5-18'
    $pools = '*S-1-5-32-568'

    # Any identity whose SID resolves has an account behind it on this machine.
    # IIS_IUSRS is a built-in alias and is normally always there, but a machine
    # stripped of IIS may not have it, and icacls refuses to grant to a SID it
    # cannot resolve. Granting it is reported rather than assumed.
    $poolsPresent = $true
    try {
        [void](New-Object System.Security.Principal.SecurityIdentifier('S-1-5-32-568')).Translate([System.Security.Principal.NTAccount])
    }
    catch {
        $poolsPresent = $false
    }

    foreach ($target in $Targets) {
        $path = $target.Path
        if (-not [System.IO.File]::Exists($path)) { continue }

        $name = $target.Label
        $ok = $true

        & icacls.exe $path /inheritance:r *> $null
        if ($LASTEXITCODE -ne 0) { $ok = $false }

        & icacls.exe $path /grant:r ($operator + ':(F)') *> $null
        if ($LASTEXITCODE -ne 0) { $ok = $false }

        & icacls.exe $path /grant ($system + ':(R)') *> $null
        if ($LASTEXITCODE -ne 0) { $ok = $false }

        if ($poolsPresent) {
            & icacls.exe $path /grant ($pools + ':(R)') *> $null
            if ($LASTEXITCODE -ne 0) { $ok = $false }
        }

        if (-not $ok) {
            Write-Host ('  {0,-24} permissions unchanged: the entries could not be set' -f $name)
            continue
        }

        $reach = 'the operator and SYSTEM'
        if ($poolsPresent) { $reach = 'the operator, SYSTEM and IIS''s worker identities' }
        Write-Host ('  {0,-24} readable by {1}' -f $name, $reach)
    }
}

<#
    .SYNOPSIS
    Writes everything configure.bat collected.
#>
function Invoke-Configuration {
    $prefix = $env:RMS_ENV_PREFIX
    if ([string]::IsNullOrEmpty($prefix)) {
        throw 'the caller did not say which variables hold the settings'
    }

    $minimum = 0
    if (-not [int]::TryParse($env:RMS_CRED_MINIMUM, [ref]$minimum)) { $minimum = 0 }

    $names = @($env:RMS_CRED_NAMES -split ';' | Where-Object { $_ -ne '' })
    $variables = @($env:RMS_CRED_VARS -split ';' | Where-Object { $_ -ne '' })
    $generate = @($env:RMS_CRED_GENERATE -split ';' | Where-Object { $_ -ne '' })
    $managed = @($env:RMS_ENV_KEYS -split ';' | Where-Object { $_ -ne '' })

    # Both environment files are named .env, so the report names them by what they
    # are rather than by their file name, which would print the same twice.
    $scannerLabel = 'scanner .env'
    $rootLabel = 'repository .env'

    $credentials = Write-CredentialFiles `
        -Directory $env:RMS_CRED_DIR `
        -Names $names `
        -Variables $variables `
        -Generate $generate `
        -Minimum $minimum

    $values = Get-EnvironmentValues $prefix

    # The API's key is one value in two places: the file the API is told to read
    # it from, and the SCANNER_API_KEY a scanner started by hand picks up. They
    # are written from the same source here so that the pair cannot disagree
    # because one of them was generated and the other was typed.
    if ($credentials.ContainsKey('api-key')) {
        $values['SCANNER_API_KEY'] = $credentials['api-key']
    }

    $targets = New-Object System.Collections.Generic.List[object]
    foreach ($name in $credentials.Keys) {
        $targets.Add(@{ Path = [System.IO.Path]::Combine($env:RMS_CRED_DIR, $name); Label = $name })
    }

    Write-Host ''
    Update-EnvironmentFile -Base $env:RMS_ENV_BASE -Target $env:RMS_ENV_TARGET -Label $scannerLabel -Values $values -Managed $managed
    $targets.Add(@{ Path = $env:RMS_ENV_TARGET; Label = $scannerLabel })

    if (-not [string]::IsNullOrEmpty($env:RMS_ROOT_TARGET)) {
        Update-EnvironmentFile -Base $env:RMS_ROOT_BASE -Target $env:RMS_ROOT_TARGET -Label $rootLabel -Values $values -Managed $managed
        $targets.Add(@{ Path = $env:RMS_ROOT_TARGET; Label = $rootLabel })
    }

    if ($env:RMS_HARDEN -eq '1') {
        Write-Host ''
        Set-RestrictedPermissions -Targets $targets
    }
}

try {
    Invoke-Configuration
    exit 0
}
catch {
    Write-Host ''
    Write-Host ('  the run stopped here: ' + $_.Exception.Message)
    Write-Host '  anything written before that point is on disk and is listed above.'
    exit 4
}
